// ── Helper: generate 7-day forecast from a base score ────────────
function makeForecast(baseScore: number): ForecastDay[] {
  const days = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  const today = new Date();
  return Array.from({ length: 7 }, (_, i) => {
    const d = new Date(today);
    d.setDate(d.getDate() + i);
    const jitter = Math.round((Math.random() - 0.5) * 20);
    const score = Math.max(5, Math.min(100, baseScore + jitter));
    return {
      date: d.toISOString().slice(0, 10),
      dayLabel: i === 0 ? 'Today' : days[d.getDay()],
      score,
      highTemp: 62 + Math.round(Math.random() * 12),
      lowTemp: 42 + Math.round(Math.random() * 10),
      weather: ['Sunny', 'Partly Cloudy', 'Cloudy', 'Rainy'][Math.floor(Math.random() * 4)],
      weatherIcon: (['sunny', 'partly-cloudy', 'cloudy', 'rainy'] as const)[
        Math.floor(Math.random() * 4)
      ],
      windSpeed: 3 + Math.round(Math.random() * 15),
      precipChance: Math.round(Math.random() * 60),
    };
  });
}


